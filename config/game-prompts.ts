export const K2_FEW_SHOT: FewShotExample[] = K1_FEW_SHOT

// 生成K2动态Prompt的函数
export function generateK2Prompt(selectedCategories: string[]): string {
  // 生成详细描述文本
  const forbiddenElementsText = selectedCategories.map(category => {
    const description = CATEGORY_DESCRIPTIONS[category as keyof typeof CATEGORY_DESCRIPTIONS]
    return `${category}（${description}）`
  }).join('、')

  // 生成简单类别列表
  const simpleCategoriesText = selectedCategories.join('、')

  return K2_PROMPT_TEMPLATE
    .replace('{{FORBIDDEN_CATEGORIES_TEXT}}', forbiddenElementsText)
    .replace('{{FORBIDDEN_CATEGORIES_SIMPLE}}', simpleCategoriesText)
}

// 获取当前阶段的配置
export function getStageConfig(stage: 'K1' | 'K2', selectedCategories: string[]) {
  return {
    prompt: stage === 'K1' ? K1_PROMPT : generateK2Prompt(selectedCategories),
    fewShot: stage === 'K1' ? K1_FEW_SHOT : K2_FEW_SHOT
  }
} 